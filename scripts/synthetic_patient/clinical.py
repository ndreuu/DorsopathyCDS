#!/usr/bin/env python3
"""Create deliberately synthetic questionnaire, clinician form and MRI phantom.

No patient data, model inference or diagnostic labels are generated. These inputs
use existing documented provider profiles unchanged. MRI pixels and its known
synthetic anatomy mask are embedded in mri.source-grid.v1; this is not raw MRI.
"""
import argparse
from copy import deepcopy
import json
import math
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / 'src'))
from dorsopathy_modules.complaints.screening import validate_source
from dorsopathy_modules.mri_anatomy.synthetic import synthetic_source

SUBJECT = 'SYNTHETIC-PATIENT-001'
SESSION = 'SYNTHETIC-SESSION-001'
PROTOCOL = 'synthetic-patient-v1'
TIME = '2026-01-01T12:00:00+00:00'


def _write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2,
                              allow_nan=False) + '\n', encoding='utf-8')


def generate(destination):
    destination = Path(destination)
    complaints = json.loads((REPO / 'examples/complaints_screening/source.json').read_text())
    complaints.update(acquired_at=TIME, assessment_ref='synthetic-patient-001-screening',
                      form_id='synthetic-patient-v1-screening', form_version='1.0.0')
    complaints['author']['id'] = SUBJECT
    complaints['answers']['duration'] = {'assessment_status': 'assessed', 'value': 3, 'unit': 'd'}
    complaints['bodymap'] = {'assessment_status': 'assessed', 'selected_regions': ['lower_back']}
    # Severe pain is an explicit synthetic patient's answer, not inferred from NRS.
    validate_source(complaints)
    _write(destination / 'inputs/complaints/source.json', complaints)

    clinical = json.loads((REPO / 'examples/clinical_exam/source_no_mri.json').read_text())
    clinical.update(acquired_at=TIME, assessment_ref='synthetic-patient-001-clinical-exam')
    clinical['author']['id'] = 'SYNTHETIC-CLINICIAN-001'
    clinical['facts']['clinical.specific_cause_warning_signs_absent'] = {
        'assessment_status': 'assessed', 'value': False}
    clinical['facts']['clinical.radiculopathy_signs_and_positive_tension_tests'] = {
        'assessment_status': 'assessed', 'value': True}
    clinical['facts']['imaging.study_status'] = {
        'assessment_status': 'assessed', 'value': 'performed_result_available'}
    clinical['facts']['clinical.imaging_clinical_concordance'] = {
        'assessment_status': 'not_assessed', 'value': None, 'reviewed_result_id': None}
    _write(destination / 'inputs/clinical_exam/source.json', clinical)

    phantom = synthetic_source()
    shape, spacing, center = 96, 0.8, 47.5
    # Ellipse of known synthetic physical geometry; an anatomy mask is supplied,
    # not predicted. Grayscale background and annulus are algorithmic phantom pixels.
    image, mask = [], []
    for row in range(shape):
        image_row, mask_row = [], []
        for col in range(shape):
            x, y = col - center, row - center
            ellipse = (x / 11.0) ** 2 + (y / 8.0) ** 2
            body = max(0.0, 1.0 - ((x / 40.0) ** 2 + (y / 34.0) ** 2))
            ring = math.exp(-((math.sqrt((x / 16.0) ** 2 + (y / 13.0) ** 2) - 1.0) / 0.2) ** 2)
            image_row.append(round(20.0 + body * 45.0 + ring * 80.0 +
                                   (150.0 if ellipse <= 1.0 else 0.0), 6))
            mask_row.append(int(ellipse <= 1.0))
        image.append(image_row); mask.append(mask_row)
    phantom['acquired_at'] = TIME
    phantom['comparison_metadata'] = {
        'schema_version': '1.0', 'subject_ref': SUBJECT, 'session_ref': SESSION,
        'protocol_id': PROTOCOL, 'linkage_evidence_refs': [],
        'acquired_interval': {'start': TIME, 'end': TIME, 'clock_domain': 'UTC'},
        'event_id': None, 'pose_id': 'synthetic-static-supine',
        'calibration_status': 'verified',
        'frame': {'id': 'synthetic-DICOM-LPS-mm', 'units': 'mm', 'axes': ['L', 'P', 'S']},
        'transform_refs': [], 'calibration_evidence_refs': [], 'clock_evidence_refs': []}
    phantom['provenance'].update(
        generator='synthetic-patient-v1',
        mask_origin='known ellipse rasterized by formula; not segmentation inference',
        inference='not_run')
    phantom['warnings'] = [
        'SYNTHETIC PHANTOM: pixels and the supplied anatomy mask were generated by formula.',
        'No MRI pathology model is run; this input tests geometric measurements only.']
    frame = phantom['frames'][0]
    frame.update(image=image, mask=mask, frame_kind='synthetic_native_axial_plane')
    frame['geometry'] = {'shape_rc': [shape, shape], 'pixel_spacing_rc_mm': [spacing, spacing],
                         'origin_lps': [0.0, 0.0, 0.0],
                         'row_direction_lps': [0.0, 1.0, 0.0],
                         'column_direction_lps': [1.0, 0.0, 0.0]}
    frame['measurements'][0]['measurement_id'] = 'synthetic-patient-001-canal-L4-L5'
    _write(destination / 'inputs/mri/source.json', phantom)
    expected = {
        'schema_version': '1.0', 'subject_ref': SUBJECT, 'session_ref': SESSION,
        'protocol_id': PROTOCOL, 'acquired_at': TIME,
        'origins': ['synthetic_demo'],
        'mri': {'module_id': 'mri.anatomy', 'module_version': '0.1.0',
                'processing_mode': 'replay', 'model': None, 'inference': 'not_run',
                'pixel_count': sum(sum(row) for row in mask),
                'expected_area_mm2': sum(sum(row) for row in mask) * spacing * spacing,
                'numbering_status': 'needs_confirmation'},
        'rules': {'nice_ng127_cauda_equina_referral': 'met', 'ru_777_radiculopathy_triad': 'not_met'},
        'clinical_concordance': 'not_assessed',
        'clinical_result_binding': 'none: concordance is explicitly unknown',
        'identity_binding': 'complaints and clinical source profiles are strict and have no subject/session fields; synthetic episode linkage plus case-level identity manifest required',
        'warning': 'Met is a referral trigger, not a cauda-equina diagnosis. Not-met triad does not exclude dorsopathy.'}
    _write(destination / 'clinical-expected.json', expected)
    return [
        {'module_id': 'complaints', 'module_version': '0.2.0',
         'source_path': 'inputs/complaints/source.json', 'artifacts': [], 'parameters': {}},
        {'module_id': 'clinical.exam', 'module_version': '0.1.0',
         'source_path': 'inputs/clinical_exam/source.json', 'artifacts': [], 'parameters': {}},
        {'module_id': 'mri.anatomy', 'module_version': '0.1.0',
         'source_path': 'inputs/mri/source.json', 'artifacts': [],
         'parameters': {'processing_mode': 'replay'}},
    ]


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    arguments = parser.parse_args()
    print(json.dumps(generate(arguments.output), ensure_ascii=False))
